@Injectable({ providedIn: 'root' })
export class TranslationService {
  private langSubject = new BehaviorSubject<Lang>(
    (localStorage.getItem('lang') as Lang) || 'fr'
  );

  lang$ = this.langSubject.asObservable();

  get lang(): Lang {
    return this.langSubject.value;
  }

  set lang(l: Lang) {
    this.langSubject.next(l);
    localStorage.setItem('lang', l);
  }

  /**
   * Traduit une clé, avec substitution optionnelle de paramètres `{{ nom }}`.
   *
   *     t('toast.reservation.cancelled', { name: 'Le Petit Prince' })
   */
  t(key: string, params?: Record<string, string | number>): string {
    const template = TRANSLATIONS[this.lang][key] || key;
    if (!params) {
      return template;
    }
    return Object.keys(params).reduce(
      (acc, name) => acc.split(`{{ ${name} }}`).join(String(params[name])),
      template
    );
  }

  toggleLang(): void {
    this.lang = this.lang === 'fr' ? 'en' : 'fr';
  }
}
